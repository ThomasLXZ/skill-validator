import { AI_CRAWLERS, POLICY_TOKEN } from "./crawlers";
import { serializePrefs, type AiprefLabel } from "./aipref";

export type Access = "allow" | "block" | "default";

export interface GeneratorOptions {
  /** Per-crawler choice. "default" = no group, falls back to `User-agent: *`. */
  access: Record<string, Access>;
  /** Content-Usage preferences (draft-ietf-aipref-attach). Omitted labels are not written. */
  contentUsage: Partial<Record<AiprefLabel, "y" | "n">>;
  /** Add the draft `__usage_ai-training` group. */
  policyToken: "none" | "against" | "in-favor";
  /** Paths that stay open for training even when the policy token says against. */
  policyTokenAllow: string[];
  sitemap: string;
}

export type Preset = "block-training" | "block-all-ai" | "allow-all";

export function presetAccess(preset: Preset): Record<string, Access> {
  const out: Record<string, Access> = {};
  for (const c of AI_CRAWLERS) {
    if (c.legacy) { out[c.token] = "default"; continue; }
    out[c.token] = preset === "allow-all" ? "default" : preset === "block-all-ai" ? "block" : c.purpose === "training" ? "block" : "default";
  }
  return out;
}

export function defaultOptions(): GeneratorOptions {
  return { access: presetAccess("block-training"), contentUsage: { "train-ai": "n" }, policyToken: "against", policyTokenAllow: [], sitemap: "" };
}

export function generateRobots(o: GeneratorOptions): string {
  const cu = serializePrefs(o.contentUsage);
  const cuLine = cu ? `Content-Usage: ${cu}` : "";
  const tokens = (a: Access) => AI_CRAWLERS.filter((c) => (o.access[c.token] ?? "default") === a).map((c) => c.token);
  const blocks: string[] = ["# robots.txt generated by Skill Validator tools"];

  const blocked = tokens("block");
  if (blocked.length) blocks.push(["# AI crawlers: no access", ...blocked.map((t) => `User-agent: ${t}`), "Disallow: /"].join("\n"));

  const allowed = tokens("allow");
  if (allowed.length) blocks.push(["# AI crawlers: explicit access", ...allowed.map((t) => `User-agent: ${t}`), "Allow: /", ...(cuLine ? [cuLine] : [])].join("\n"));

  if (o.policyToken !== "none") {
    const lines = ["# Draft shared AI-training preference (not a crawl rule)", `User-agent: ${POLICY_TOKEN}`];
    if (o.policyToken === "against") {
      lines.push("Disallow: /");
      for (const p of o.policyTokenAllow.map((s) => s.trim()).filter(Boolean)) lines.push(`Allow: ${p.startsWith("/") ? p : "/" + p}`);
    } else lines.push("Allow: /");
    blocks.push(lines.join("\n"));
  }

  blocks.push(["# Everyone else", "User-agent: *", "Allow: /", ...(cuLine ? [cuLine] : [])].join("\n"));
  if (o.sitemap.trim()) blocks.push(`Sitemap: ${o.sitemap.trim()}`);
  return blocks.join("\n\n") + "\n";
}
